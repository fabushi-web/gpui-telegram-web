export const TRANSLATIONS: Record<LocaleCode, Record<TranslationKey, string>> = {
  'en-US': EN_US,
  'zh-CN': ZH_CN,
};

let currentActiveLocale: LocaleCode = 'en-US';

export function normalizeLocale(raw?: string | null): LocaleCode {
  if (!raw) return 'en-US';
  const lower = raw.toLowerCase();
  if (lower.startsWith('zh')) return 'zh-CN';
  return 'en-US';
}

export function setActiveLocale(locale: LocaleCode): void {
  currentActiveLocale = normalizeLocale(locale);
  if (typeof document !== 'undefined') {
    document.documentElement.lang = currentActiveLocale;
  }
}

export function getActiveLocale(): LocaleCode {
  return currentActiveLocale;
}

export function getDictionary(locale: LocaleCode = currentActiveLocale): Record<TranslationKey, string> {
  return TRANSLATIONS[normalizeLocale(locale)];
}

export function t(
  key: TranslationKey | (string & {}),
  localeOrParams?: LocaleCode | Record<string, string | number>,
  maybeParams?: Record<string, string | number>,
): string {
  const isLocaleArg =
    typeof localeOrParams === 'string' &&
    (localeOrParams === 'en-US' || localeOrParams === 'zh-CN');
  const locale: LocaleCode = isLocaleArg
    ? localeOrParams
    : currentActiveLocale;
  const params = isLocaleArg
    ? maybeParams
    : (localeOrParams as Record<string, string | number> | undefined);

  const dict = TRANSLATIONS[locale] ?? EN_US;
  const fallback = EN_US[key as TranslationKey] ?? String(key);
  let template = dict[key as TranslationKey] ?? fallback;

  if (params) {
    for (const [k, v] of Object.entries(params)) {
      template = template.replaceAll(`{${k}}`, String(v));
    }
  }
  return template;
}

export function formatDurationClock(seconds: number): string {
  const safe = Math.max(0, Math.floor(Number.isFinite(seconds) ? seconds : 0));
  const mins = Math.floor(safe / 60);
  const secs = safe % 60;
  return `${mins}:${String(secs).padStart(2, '0')}`;
}

export function formatChatTimestamp(
  timestampMs?: number,
  locale: LocaleCode = currentActiveLocale,
): string {
  if (!timestampMs || !Number.isFinite(timestampMs)) return '';
  const date = new Date(timestampMs);
  const now = new Date();
  const sameDay =
    date.getFullYear() === now.getFullYear() &&
    date.getMonth() === now.getMonth() &&
    date.getDate() === now.getDate();

  if (sameDay) {
    return date.toLocaleTimeString(locale, {
      hour: '2-digit',
      minute: '2-digit',
      hour12: false,
    });
  }

  const diffDays = Math.floor((now.getTime() - date.getTime()) / 86_400_000);
  if (diffDays >= 0 && diffDays < 7) {
    return date.toLocaleDateString(locale, { weekday: 'short' });
  }

  return date.toLocaleDateString(locale, {
    month: 'short',
    day: 'numeric',
  });
}
